package com.anilibrix.plus.core.sync

/**
 * Отправка статуса и прогресса во внешний трекер.
 *
 * Вынесено за интерфейс, потому что синхронизация с Shikimori включается
 * только после привязки аккаунта, а очередь работает всегда. Без интерфейса
 * [SyncProcessor] пришлось бы на каждой операции спрашивать «а привязан ли
 * аккаунт», и знание о конкретном трекере растеклось бы по всему обработчику.
 */
interface ShikimoriSyncHandler {
    /**
     * @return `true`, если операцию можно считать закрытой — в том числе когда
     * аккаунт не привязан и отправлять некуда. Возврат `false` означает
     * «повторить позже».
     */
    suspend fun push(operation: PendingOperation): Boolean
}
